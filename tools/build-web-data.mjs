/**
 * build-web-data.mjs — turns data/units.json into web/data.js.
 *
 * data/units.json is generated from the game files by extractor/build-site-data.mjs and
 * committed (CI cannot read the game). This script only packages it for the page.
 *
 * Why not load the JSON directly: when index.html is opened by double-click,
 * the browser uses file:// and fetch('data/units.json') hits CORS. So the data
 * is embedded into a plain script as window.TR_DATA — that always works.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { toGlobalScript } from './calc-global.mjs';
import { configScript } from './site-config.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'data');
const WEB = join(ROOT, 'web');

const doc = JSON.parse(await readFile(join(DATA, 'units.json'), 'utf8'));

// Unit and structure descriptions are never published. The generator does not write
// them; this is the last line of defence should one ever appear in the data.
const units = doc.units.map(({ description, desc, ...unit }) => unit);

const payload = {
  meta: doc.meta,
  units,
  effects: doc.effects ?? {},
  doctrines: doc.doctrines ?? {},
};

await mkdir(join(WEB, 'lib'), { recursive: true });
await writeFile(
  join(WEB, 'data.js'),
  `// GENERATED by tools/build-web-data.mjs from data/units.json — do not edit by hand.\n` +
    `// Source: ${payload.meta.source}\n` +
    `// Generated: ${payload.meta.generatedAt}\n` +
    `window.TR_DATA = ${JSON.stringify(payload)};\n`,
  'utf8',
);

// calc.js → classic script, otherwise file:// will not allow loading the module.
const calcSource = await readFile(join(ROOT, 'web/lib/calc.js'), 'utf8');
await writeFile(join(WEB, 'lib/calc.global.js'), toGlobalScript(calcSource), 'utf8');

// Build settings for the page. The local copy defaults to Russian; the public one
// (tools/build-public.mjs) writes its own config.js with English into dist/.
await writeFile(join(WEB, 'config.js'), configScript({ defaultLang: 'ru', public: false }), 'utf8');

const kb = async (name) => (await readFile(join(WEB, name))).length / 1024;
console.log(`web/data.js            — ${(await kb('data.js')).toFixed(0)} KB, ${payload.units.length} entities`);
console.log(`web/lib/calc.global.js — ${(await kb('lib/calc.global.js')).toFixed(0)} KB`);
console.log('Open web/index.html by double-click.');
