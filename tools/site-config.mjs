/**
 * site-config.mjs — contents of config.js, which the page reads before anything
 * else (window.TR_CONFIG). One function for both builds, so the local and the
 * public build cannot drift apart in their set of fields.
 *
 *   defaultLang — language used until the user picks one: 'ru' | 'en'
 *   public      — true for the GitHub Pages build (exposed as TRI18n.isPublic)
 *   repoUrl     — link to the source code in the footer (optional)
 */
export function configScript({ defaultLang, public: isPublic, repoUrl = null }) {
  const config = { defaultLang, public: Boolean(isPublic), ...(repoUrl ? { repoUrl } : {}) };
  return `// GENERATED by tools/site-config.mjs — do not edit by hand.\nwindow.TR_CONFIG = ${JSON.stringify(config)};\n`;
}
